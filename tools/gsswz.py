def _map(W,H):
    """반환: PSMT4 (y,x) -> 선형 데이터 내 니블 인덱스"""
    bw32=W//128*2   # CT32 버퍼 폭(64px 단위): PSMT4 페이지(128px)=CT32 페이지(64px)
    cw=bw32*64      # CT32 이미지 폭(픽셀)
    # CT32: 선형 워드 i -> (x,y) -> vram 워드
    n32=W*H//8
    lin2vram=np.empty(n32,np.int64)
    ys,xs=np.divmod(np.arange(n32),cw)
    page=(ys//32)*bw32+xs//64
    blk=np.array(BT32)[(ys%32)//8,(xs%64)//8];col=np.array(CT32)[ys%8,xs%8]
    lin2vram[:]=page*2048+blk*64+col
    vram2lin=np.empty(lin2vram.max()+1,np.int64);vram2lin[lin2vram]=np.arange(n32)
    # PSMT4 (x,y) -> vram 니블
    y,x=np.mgrid[0:H,0:W]
    bw4=W//64;page=(y//128)*(bw4//2)+x//128
    blk=np.array(BT4)[(y%128)//16,(x%128)//32];col=np.array(CT4)[y%16,x%32]
    nib=page*16384+blk*512+col
    word=nib//8;sub=nib%8
    return vram2lin[word]*8+sub
def unswizzle(data,W,H):
    m=_map(W,H);raw=np.frombuffer(data[:W*H//2],np.uint8)
    nibs=np.empty(raw.size*2,np.uint8);nibs[0::2]=raw&15;nibs[1::2]=raw>>4
    return nibs[m]
def swizzle(px,W,H):
    m=_map(W,H);nibs=np.zeros(W*H,np.uint8);nibs[m]=px
    return (nibs[0::2]|(nibs[1::2]<<4)).astype(np.uint8).tobytes()

def _map8(w,h):
    y,x=np.mgrid[0:h,0:w]
    block=(y&~0xf)*w+(x&~0xf)*2
    swap=(((y+2)>>2)&1)*4
    posY=(((y&~3)>>1)+(y&1))&7
    col=posY*w*2+((x+swap)&7)*4
    byte=((y>>1)&1)+((x>>2)&2)
    return block+col+byte
def unswizzle8(buf,w,h):
    return np.frombuffer(buf[:w*h],np.uint8)[_map8(w,h)]
def swizzle8(img,w,h):
    out=np.zeros(w*h,np.uint8);out[_map8(w,h).reshape(-1)]=img.reshape(-1);return out.tobytes()
