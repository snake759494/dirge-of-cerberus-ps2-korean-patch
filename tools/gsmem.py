import numpy as np
BT32=np.array([[0,1,4,5,16,17,20,21],[2,3,6,7,18,19,22,23],[8,9,12,13,24,25,28,29],[10,11,14,15,26,27,30,31]])
CT32=np.array([[0,1,4,5,8,9,12,13],[2,3,6,7,10,11,14,15],[16,17,20,21,24,25,28,29],[18,19,22,23,26,27,30,31],
      [32,33,36,37,40,41,44,45],[34,35,38,39,42,43,46,47],[48,49,52,53,56,57,60,61],[50,51,54,55,58,59,62,63]])
BT8=BT32
_c8=[[0,4,16,20,32,36,48,52,2,6,18,22,34,38,50,54],[8,12,24,28,40,44,56,60,10,14,26,30,42,46,58,62],
     [33,37,49,53,1,5,17,21,35,39,51,55,3,7,19,23],[41,45,57,61,9,13,25,29,43,47,59,63,11,15,27,31],
     [96,100,112,116,64,68,80,84,98,102,114,118,66,70,82,86],[104,108,120,124,72,76,88,92,106,110,122,126,74,78,90,94],
     [65,69,81,85,97,101,113,117,67,71,83,87,99,103,115,119],[73,77,89,93,105,109,121,125,75,79,91,95,107,111,123,127]]
CT8=np.array(_c8+[[v+128 for v in r] for r in _c8])
BT4=np.array([[0,2,8,10],[1,3,9,11],[4,6,12,14],[5,7,13,15],[16,18,24,26],[17,19,25,27],[20,22,28,30],[21,23,29,31]])
from gsswz import CT4 as _ct4
CT4=np.array(_ct4)
def addr32(x,y,bw):   # 워드 주소, bw: 64px 단위
    return ((y//32)*bw+x//64)*2048+BT32[(y%32)//8,(x%64)//8]*64+CT32[y%8,x%8]
def addr8(x,y,bw):    # 바이트 주소, 페이지 128x64
    return ((y//64)*(bw//2)+x//128)*8192+BT8[(y%64)//16,(x%128)//16]*256+CT8[y%16,x%16]
def addr4(x,y,bw):    # 니블 주소, 페이지 128x128
    return ((y//128)*(bw//2)+x//128)*16384+BT4[(y%128)//16,(x%128)//32]*512+CT4[y%16,x%32]
